"""Per-pair reference counts and top-20 candidate ceilings of every dataset (#139).

Loads every pair through :func:`load_dataset` and its stored top-20 candidate
lists exactly as the experiments do (``reference_statistics.audit_dataset``)
and records, per pair:

* the validation and test reference counts and reference-source counts (the
  denominators of Recall@k and of MRR/Hits@k), and how many test sources have
  several gold targets;
* the **ranking ceiling**: the fraction of test reference sources with any
  gold target in their list, the most MRR and Hits@k can reach;
* **candidate recall@20**: the fraction of test references whose target is in
  its source's list, the most Recall@k can reach;
* the **F1 recall ceiling**: one prediction per source can recover at most one
  reference per listed source, so ``sources with a listed gold / references``.

Writes ``metric_ceilings.json`` (read by the results table and figures through
``kgsemembed.evaluation.reference_counts``) and ``metric_ceilings.md``.  No
model is loaded and nothing is written under ``data/``.

Usage
-----
python scripts/metric_ceilings.py --data_dir data/ --output_dir artifacts/issue-139/
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path
from typing import Dict, List

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.reference_statistics import PairAudit, audit_dataset  # noqa: E402

_ALL_DATASETS = ("D1", "D2", "D3", "D4", "D5")


def pair_counts(audit: PairAudit) -> Dict[str, object]:
    """
    Summarise one pair's reference counts and candidate ceilings.

    Parameters
    ----------
    audit : PairAudit
        Audit of the pair against its stored candidate lists.

    Returns
    -------
    Dict[str, object]
        Counts and the three ceilings, keyed as in ``metric_ceilings.json``.
    """
    val, test = audit.populations["validation"], audit.populations["test"]
    return {
        "dataset_id": audit.dataset_id, "pair_name": audit.pair_name,
        "n_val_refs": val.refs, "n_val_reference_sources": val.ref_sources,
        "n_test_refs": test.refs, "n_test_reference_sources": test.ref_sources,
        "n_test_multi_target_sources": test.ref_sources - test.gold_per_source.get("1", 0),
        "n_test_sources_gold_listed": test.gold_listed, "n_test_refs_listed": test.refs_listed,
        "ranking_ceiling": test.gold_listed / test.ref_sources,
        "candidate_recall_at_20": test.refs_listed / test.refs,
        "f1_recall_ceiling": test.gold_listed / test.refs,
    }


def _row(counts: Dict[str, object]) -> str:
    """Render one pair as a Markdown table row."""
    cells = [counts["dataset_id"], counts["pair_name"]]
    cells += [f"{counts[key]:,}" for key in ("n_val_refs", "n_test_refs", "n_test_reference_sources",
                                             "n_test_multi_target_sources")]
    cells += [f"{counts[key]:.4f}" for key in ("ranking_ceiling", "candidate_recall_at_20", "f1_recall_ceiling")]
    return "| " + " | ".join(cells) + " |"


def build_report(rows: List[Dict[str, object]]) -> List[str]:
    """
    Render the per-pair counts and ceilings as Markdown.

    Parameters
    ----------
    rows : List[Dict[str, object]]
        Output of :func:`pair_counts` for every pair.

    Returns
    -------
    List[str]
        Report lines.
    """
    return [
        "# Reference counts and top-20 candidate ceilings (#139)", "",
        "Generated by `scripts/metric_ceilings.py`. Test population only, stored stage-1 lists.",
        "Ranking ceiling: test reference sources with a gold target in their list (caps MRR, Hits@k).",
        "Recall@20: test references whose target is listed (caps Recall@k). F1 recall ceiling:",
        "listed sources / references (one prediction per source).", "",
        "| Dataset | Pair | Val refs | Test refs | Test ref sources | 1:N sources | Ranking ceiling "
        "| Recall@20 | F1 recall ceiling |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
        *[_row(row) for row in rows], "",
    ]


def _build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Write per-pair reference counts and candidate ceilings.")
    parser.add_argument("--datasets", nargs="+", default=list(_ALL_DATASETS), choices=_ALL_DATASETS)
    parser.add_argument("--data_dir", default="data/", help="Dataset root directory.")
    parser.add_argument("--output_dir", default="artifacts/issue-139/", help="Output directory.")
    return parser


def main() -> None:
    """Write ``metric_ceilings.json`` and ``metric_ceilings.md``."""
    random.seed(42)
    np.random.seed(42)
    args = _build_arg_parser().parse_args()
    data_dir, output_dir = Path(args.data_dir), Path(args.output_dir)
    rows = [pair_counts(audit) for dataset_id in args.datasets for audit in audit_dataset(dataset_id, data_dir)]
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "metric_ceilings.json").write_text(json.dumps({"pairs": rows}, indent=2) + "\n", encoding="utf-8")
    (output_dir / "metric_ceilings.md").write_text("\n".join(build_report(rows)), encoding="utf-8")
    print(f"Wrote {output_dir / 'metric_ceilings.json'} and metric_ceilings.md")


if __name__ == "__main__":
    main()
