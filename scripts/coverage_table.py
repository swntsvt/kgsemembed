"""Condition × column coverage of the stored results (#163).

Lists every registered condition (C1–C20, C12 retired) against the six
dataset columns and states, per cell, whether it was run (with its pair
count), left out by design (with the reason fixed on #163), or registered but
without results.  A cell that is neither registered nor justified by a reason
in :data:`BY_DESIGN` raises, so every gap in the matrix is either filled or
explained.

The cells are read from the registry and the result files only, so the output
regenerates byte-identically from the same results.

Usage
-----
python scripts/coverage_table.py --results_dir data/results/ \\
    --output artifacts/issue-163/coverage.md
"""

from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from kgsemembed.evaluation.stats import expand_dataset_ids  # noqa: E402
from kgsemembed.pipeline.conditions import EXPERIMENT_CONDITIONS, ExperimentCondition  # noqa: E402

COLUMNS = ("D1", "D2", "D3", "D4_schema", "D4_instance", "D5")
RESULT_SUFFIX = "_results.json"

_M4 = "a", "M4 (BioLORD) is a biomedical model, run on the biomedical datasets D1 and D2."
_INSTANCE = "b", (
    "Instance-oriented strategy, run on the datasets with instances, D4 (whose loader also "
    "yields the schema column) and D5: V4 always uses the instance tier list and V5 walks "
    "instance neighbourhoods."
)
_LONG_CONTEXT = "c", (
    "Group D tests the long-context model M3 without a token budget: C14 where texts are "
    "longest (D5), C15 on D1 and D2 for Figure 2's model comparison."
)
_SANITY = "d", "Sanity check that must reproduce C10 on D1; not a compared condition."

BY_DESIGN: Dict[str, Tuple[str, str]] = {
    "C6": _M4, "C11": _M4, "C16": _M4, "C17": _M4,
    "C5": _INSTANCE, "C8": _INSTANCE,
    "C14": _LONG_CONTEXT, "C15": _LONG_CONTEXT,
    "C19": _SANITY,
}

_TITLE = "# Condition × column coverage"
_PROVENANCE = (
    "Generated by `scripts/coverage_table.py` (#163) from the registry "
    "(`pipeline/conditions.py`) and the result files. A number is the pairs run "
    "(D3 has 21); a letter marks a column left out by design, with the reason below."
)
_RULE = (
    "**Coverage rule.** Every condition runs on every column unless a stated reason "
    "excludes it: a biomedical model on the biomedical datasets, an "
    "instance-oriented strategy on the instance columns, the no-budget model where "
    "texts are longest, and the sanity check on the column it reproduces. Paired tests "
    "compare two conditions only on a column both were run on, and the tables' Mean* "
    "is printed only for conditions run on every D1–D4 column."
)


def pair_count(results_dir: Path, condition_id: str, column: str) -> int:
    """
    Count the result files of one condition on one column.

    Parameters
    ----------
    results_dir : Path
        Root of the C1–C20 results.
    condition_id : str
        Registered condition ID.
    column : str
        One of :data:`COLUMNS`.

    Returns
    -------
    int
        Number of ``*_results.json`` files, one per pair.
    """
    return len(list((results_dir / condition_id / column).glob(f"*{RESULT_SUFFIX}")))


def cell(results_dir: Path, condition: ExperimentCondition, column: str) -> str:
    """
    Render one condition × column cell.

    Parameters
    ----------
    results_dir : Path
        Root of the C1–C20 results.
    condition : ExperimentCondition
        The registered condition.
    column : str
        One of :data:`COLUMNS`.

    Returns
    -------
    str
        The pair count when run, ``not run`` when registered without results,
        or the by-design footnote letter.

    Raises
    ------
    ValueError
        If the column is neither registered for the condition nor justified.
    """
    if column in expand_dataset_ids(list(condition.datasets)):
        count = pair_count(results_dir, condition.condition_id, column)
        return str(count) if count else "not run"
    if condition.condition_id not in BY_DESIGN:
        raise ValueError(f"{condition.condition_id} on {column}: not registered and no reason given")
    return f"by design ({BY_DESIGN[condition.condition_id][0]})"


def table_lines(results_dir: Path) -> List[str]:
    """
    Build the coverage table, one row per registered condition in registry order.

    Parameters
    ----------
    results_dir : Path
        Root of the C1–C20 results.

    Returns
    -------
    List[str]
        Markdown table lines.
    """
    lines = [
        "| Condition | Strategy | Model | Group | " + " | ".join(COLUMNS) + " |",
        "|---|---|---|---|" + "---|" * len(COLUMNS),
    ]
    for condition in EXPERIMENT_CONDITIONS:
        cells = [cell(results_dir, condition, column) for column in COLUMNS]
        lines.append(
            f"| {condition.condition_id} | {condition.strategy_name} | {condition.model_key} "
            f"| {condition.ablation_group} | " + " | ".join(cells) + " |"
        )
    return lines


def reason_lines() -> List[str]:
    """Return one line per by-design reason, with the conditions it covers."""
    reasons: Dict[Tuple[str, str], List[str]] = {}
    for condition_id, reason in BY_DESIGN.items():
        reasons.setdefault(reason, []).append(condition_id)
    return [f"- ({letter}) {', '.join(ids)}: {text}" for (letter, text), ids in sorted(reasons.items())]


def render_markdown(results_dir: Path) -> str:
    """
    Assemble the coverage artifact.

    Parameters
    ----------
    results_dir : Path
        Root of the C1–C20 results.

    Returns
    -------
    str
        Title, provenance, table, reasons and the coverage rule, ending in one
        newline.
    """
    sections = [_TITLE, _PROVENANCE, "\n".join(table_lines(results_dir)), "\n".join(reason_lines()), _RULE]
    return "\n\n".join(sections) + "\n"


def _build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Write the condition × column coverage table.")
    parser.add_argument("--results_dir", type=Path, default=Path("data/results/"))
    parser.add_argument("--output", type=Path, default=Path("artifacts/issue-163/coverage.md"))
    return parser


def main(argv: Optional[List[str]] = None) -> None:
    """Write the coverage table."""
    random.seed(42)
    np.random.seed(42)
    args = _build_arg_parser().parse_args(argv)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_markdown(args.results_dir), encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
