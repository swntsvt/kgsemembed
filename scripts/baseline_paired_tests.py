"""Paired intervals of every condition against the stage-1 baseline B0 (#165).

Runs :func:`kgsemembed.evaluation.paired_tests.run_baseline_tests` on the
stored results and the B0 results and writes ``baseline_paired_tests.json``
(every row) and ``baseline_paired_tests.md`` (per-column MRR counts, then one
table per metric and the cells that could not be tested).

The test plan was fixed on #165 before any test ran: every registered
condition except the sanity check C19, on every column it was run on;
condition − B0 on MRR and Hits@1 (primary) and F1 (secondary); #140 units,
settings and guards; Holm on MRR across every condition compared with B0
within one column, an untested cell kept in its family with p = 1.  Takes a
few minutes (no model, no dataset); the outputs depend only on the result
trees and regenerate byte-identically.

Usage
-----
python scripts/baseline_paired_tests.py --results_dir data/results/ \\
    --baseline_dir data/results_ngram_baseline/ --output_dir artifacts/issue-165/
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path
from typing import List, Optional

import numpy as np

from kgsemembed.evaluation import paired_tests
from kgsemembed.evaluation.aggregator import baseline_section_body
from kgsemembed.evaluation.reference_counts import DEFAULT_COUNTS_PATH, load_reference_counts

_TITLE = "# Conditions against the stage-1 baseline B0"
_PROVENANCE = (
    "Generated by `scripts/baseline_paired_tests.py` (#165; plan fixed on the issue "
    "before any test ran). The text below is `report.md`'s \"Paired Tests Against "
    "B0\" section, rendered by the same function."
)


def render_markdown(rows: List[dict]) -> str:
    """
    Assemble the Markdown artifact from the test rows.

    Parameters
    ----------
    rows : List[dict]
        Output of :func:`paired_tests.run_baseline_tests`.

    Returns
    -------
    str
        Title, provenance line and :func:`baseline_section_body`, ending in
        one newline.
    """
    return f"{_TITLE}\n\n{_PROVENANCE}\n\n{baseline_section_body(rows)}\n"


def _build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Paired tests of every condition against B0.")
    parser.add_argument("--results_dir", type=Path, default=Path("data/results/"))
    parser.add_argument("--baseline_dir", type=Path, default=Path("data/results_ngram_baseline/"))
    parser.add_argument("--ceilings", type=Path, default=Path(DEFAULT_COUNTS_PATH))
    parser.add_argument("--output_dir", type=Path, default=Path("artifacts/issue-165/"))
    return parser


def main(argv: Optional[List[str]] = None) -> None:
    """Run the B0 tests and write the JSON and Markdown artifacts."""
    random.seed(42)
    np.random.seed(42)
    args = _build_arg_parser().parse_args(argv)
    counts = load_reference_counts(args.ceilings)
    rows = paired_tests.run_baseline_tests(args.results_dir, args.baseline_dir, counts)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "baseline_paired_tests.json").write_text(json.dumps(rows, indent=2) + "\n")
    (args.output_dir / "baseline_paired_tests.md").write_text(render_markdown(rows))
    print(f"Wrote {args.output_dir}/baseline_paired_tests.{{json,md}}")


if __name__ == "__main__":
    main()
