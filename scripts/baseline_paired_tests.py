"""Paired intervals of every condition against the stage-1 baseline B0 (#165).

Runs :func:`kgsemembed.evaluation.paired_tests.run_baseline_tests` on the
stored results and the B0 results and writes ``baseline_paired_tests.json``
(every row) and ``baseline_paired_tests.md`` (per-column MRR counts, then one
table per metric and the cells that could not be tested).

The test plan was fixed on #165 before any test ran: every registered
condition except the sanity check C19, on every column it was run on;
condition − B0 on MRR and Hits@1 (primary) and F1 (secondary); #140 units,
settings and guards; Holm on MRR across every condition compared with B0
within one column, an untested cell kept in its family with p = 1.  Takes a
few minutes (no model, no dataset); the outputs depend only on the result
trees and regenerate byte-identically.

Usage
-----
python scripts/baseline_paired_tests.py --results_dir data/results/ \\
    --baseline_dir data/results_ngram_baseline/ --output_dir artifacts/issue-165/
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path
from typing import Iterable, List, Optional

import numpy as np

from kgsemembed.evaluation import paired_tests
from kgsemembed.evaluation.reference_counts import DEFAULT_COUNTS_PATH, load_reference_counts
from kgsemembed.pipeline.conditions import get_condition

_HEADINGS = {"mrr": "MRR (primary)", "hits_at_1": "Hits@1 (primary)", "f1": "F1 (secondary)"}
_NO_DECISION = "—"
_SUMMARY_HEADER = (
    "Column", "Cells", "Tested", "Above B0", "Below B0", "Significant gain", "Significant loss",
)
_ROW_HEADER = (
    "Condition", "Strategy", "Model", "Column", "B0", "Condition value", "Δ", "95% CI", "p",
    "p (Holm)", "m", "Sig.", "Ceiling", "n",
)


def _fmt(value: Optional[float]) -> str:
    return "n/a" if value is None else f"{value:.4f}"


def _table(header: Iterable[str], rows: Iterable[Iterable[str]]) -> List[str]:
    header = list(header)
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return lines + ["| " + " | ".join(row) + " |" for row in rows] + [""]


def _decision_cells(row: dict) -> List[str]:
    if "p_holm" not in row:
        return [_NO_DECISION] * 3
    return [_fmt(row["p_holm"]), str(row["family_size"]), "yes" if row["significant"] else "no"]


def row_cells(row: dict) -> List[str]:
    """
    Render one tested row as table cells.

    Parameters
    ----------
    row : dict
        A tested row of :func:`paired_tests.run_baseline_tests`.

    Returns
    -------
    List[str]
        The cells of :data:`_ROW_HEADER`.
    """
    condition = get_condition(row["condition_b"])
    return [
        row["condition_b"], condition.strategy_name, condition.model_key, row["dataset_id"],
        _fmt(row["value_a"]), _fmt(row["value_b"]), f"{row['delta']:+.4f}",
        f"[{row['ci_low']:+.4f}, {row['ci_high']:+.4f}]", _fmt(row["p_value"]),
        *_decision_cells(row), _fmt(row["ceiling"]), str(row["n_units"]),
    ]


def _summary_lines(rows: List[dict]) -> List[str]:
    cells = [
        [s["dataset_id"], *(str(s[key]) for key in (
            "n_cells", "n_tested", "above", "below", "significant_gain", "significant_loss"))]
        for s in paired_tests.baseline_summary(rows)
    ]
    return ["## MRR against B0 per column", "", *_table(_SUMMARY_HEADER, cells)]


def _metric_lines(rows: List[dict], metric: str) -> List[str]:
    tested = [row_cells(r) for r in rows if r["tested"] and r["metric"] == metric]
    return [f"## {_HEADINGS[metric]}", "", *_table(_ROW_HEADER, tested)]


def _untested_lines(rows: List[dict]) -> List[str]:
    reasons = {(r["condition_b"], r["dataset_id"]): r["reason"] for r in rows if not r["tested"]}
    if not reasons:
        return ["## Not tested", "", "None: every cell was tested.", ""]
    return ["## Not tested", "", *(f"- {c} on {d}: {why}" for (c, d), why in reasons.items()), ""]


def _preamble() -> List[str]:
    settings = paired_tests.TestSettings()
    return [
        "# Conditions against the stage-1 baseline B0",
        "",
        "Generated by `scripts/baseline_paired_tests.py` (#165; plan fixed on the issue before",
        "any test ran). Δ is condition − B0, positive when re-ranking beats the stage-1 n-gram",
        f"order. {int(paired_tests.CONFIDENCE * 100)}% percentile bootstrap over test sources "
        "resampled within each pair (D3's",
        "21 pairs are strata; its value is their mean) and a paired randomisation p, two-sided;",
        f"{settings.n_replicates:,} replicates each, seed {settings.seed}. MRR and Hits@1 count "
        "test reference sources;",
        "F1 adds unmatched sources' predictions and is recomputed from TP, FP and FN. Only MRR",
        "carries a decision: Holm across every condition compared with B0 on one column",
        f"(m = the column's registered cells), alpha {paired_tests.ALPHA}; an untested cell would "
        "enter with p = 1.",
        "Hits@1 and F1 show their interval and unadjusted p (—: no decision). Intervals are not",
        "adjusted. C19, the sanity check reproducing C10, is not tested. Ceiling: the most the",
        "metric can reach on the stored top-20 lists (F1: its recall ceiling).",
        "",
    ]


def render_markdown(rows: List[dict]) -> str:
    """Assemble the Markdown artifact from the test rows."""
    lines = [*_preamble(), *_summary_lines(rows)]
    for metric in paired_tests.METRICS:
        lines += _metric_lines(rows, metric)
    return "\n".join(lines + _untested_lines(rows)).rstrip("\n") + "\n"


def _build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Paired tests of every condition against B0.")
    parser.add_argument("--results_dir", type=Path, default=Path("data/results/"))
    parser.add_argument("--baseline_dir", type=Path, default=Path("data/results_ngram_baseline/"))
    parser.add_argument("--ceilings", type=Path, default=Path(DEFAULT_COUNTS_PATH))
    parser.add_argument("--output_dir", type=Path, default=Path("artifacts/issue-165/"))
    return parser


def main(argv: Optional[List[str]] = None) -> None:
    """Run the B0 tests and write the JSON and Markdown artifacts."""
    random.seed(42)
    np.random.seed(42)
    args = _build_arg_parser().parse_args(argv)
    counts = load_reference_counts(args.ceilings)
    rows = paired_tests.run_baseline_tests(args.results_dir, args.baseline_dir, counts)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "baseline_paired_tests.json").write_text(json.dumps(rows, indent=2) + "\n")
    (args.output_dir / "baseline_paired_tests.md").write_text(render_markdown(rows))
    print(f"Wrote {args.output_dir}/baseline_paired_tests.{{json,md}}")


if __name__ == "__main__":
    main()
